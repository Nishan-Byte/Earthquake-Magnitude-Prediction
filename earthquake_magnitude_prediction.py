"""## 5. Feature Engineering
Spatial, temporal (cyclic sine/cosine), catalog-quality, historical-seismicity, and
one-hot magnitude-type features -- mirroring the report's 6 feature groups.

"""

df = df.sort_values("datetime").reset_index(drop=True)

# --- Temporal features ---
df["year"] = df["datetime"].dt.year
df["month"] = df["datetime"].dt.month
df["day"] = df["datetime"].dt.day
df["hour"] = df["datetime"].dt.hour

df["month_sin"] = np.sin(2 * np.pi * df["month"] / 12)
df["month_cos"] = np.cos(2 * np.pi * df["month"] / 12)
df["day_sin"] = np.sin(2 * np.pi * df["day"] / 31)
df["day_cos"] = np.cos(2 * np.pi * df["day"] / 31)
df["hour_sin"] = np.sin(2 * np.pi * df["hour"] / 24)
df["hour_cos"] = np.cos(2 * np.pi * df["hour"] / 24)

# --- Spatial features ---
center_lat, center_lon = df["latitude"].mean(), df["longitude"].mean()

def haversine_km(lat1, lon1, lat2, lon2):
    R = 6371.0
    lat1, lon1, lat2, lon2 = map(np.radians, [lat1, lon1, lat2, lon2])
    dlat, dlon = lat2 - lat1, lon2 - lon1
    a = np.sin(dlat / 2) ** 2 + np.cos(lat1) * np.cos(lat2) * np.sin(dlon / 2) ** 2
    return 2 * R * np.arcsin(np.sqrt(a))

df["distance_from_center_km"] = haversine_km(df["latitude"], df["longitude"], center_lat, center_lon)

# --- Historical seismicity features ---
# past_events_within_100km: count of prior events within 100km, using a spatial grid
# to keep this fast on 100K+ rows (grid-cell neighbor lookback rather than O(n^2)).
GRID_DEG = 1.0  # ~111km at the equator, coarse but adequate given 100km radius
df["_grid_lat"] = (df["latitude"] // GRID_DEG).astype(int)
df["_grid_lon"] = (df["longitude"] // GRID_DEG).astype(int)

df = df.reset_index(drop=True)
past_counts = np.zeros(len(df), dtype=int)
recent_counts = np.zeros(len(df), dtype=int)

# Build a dict: grid cell -> sorted list of (datetime, lat, lon) seen so far, filled incrementally
from collections import defaultdict
cell_history = defaultdict(list)

times = df["datetime"].values
lats = df["latitude"].values
lons = df["longitude"].values
glats = df["_grid_lat"].values
glons = df["_grid_lon"].values

for i in range(len(df)):
    glat, glon = glats[i], glons[i]
    lat_i, lon_i, t_i = lats[i], lons[i], times[i]

    # Check the 3x3 neighboring grid cells (covers >100km radius given 1-degree cells)
    total_past = 0
    total_recent = 0
    for dlat in (-1, 0, 1):
        for dlon in (-1, 0, 1):
            hist = cell_history.get((glat + dlat, glon + dlon))
            if not hist:
                continue
            for (t_hist, lat_hist, lon_hist) in hist:
                d = haversine_km(lat_i, lon_i, lat_hist, lon_hist)
                if d <= 100:
                    total_past += 1
                    days_diff = (t_i - t_hist) / np.timedelta64(1, "D")
                    if 0 <= days_diff <= 30:
                        total_recent += 1

    past_counts[i] = total_past
    recent_counts[i] = total_recent
    cell_history[(glat, glon)].append((t_i, lat_i, lon_i))

df["past_events_within_100km"] = past_counts
df["recent_local_events_30d"] = recent_counts
df = df.drop(columns=["_grid_lat", "_grid_lon"])

# --- Magnitude-type one-hot encoding ---
magtype_dummies = pd.get_dummies(df["magType"], prefix="magType").astype(int)
df = pd.concat([df, magtype_dummies], axis=1)

print("Feature engineering complete.")
print(f"Total columns: {df.shape[1]}")
df.head()

"""## 6. Train / Validation / Test Split (Chronological)
A time-ordered split (not a random shuffle) is used so the model is evaluated on
strictly later events than it was trained on -- appropriate for a seismic catalog.

"""

df = df.sort_values("datetime").reset_index(drop=True)
n = len(df)

train_frac, val_frac = 0.727, 0.1336  # matches report's ~72.7% / 13.4% / 13.9% proportions
train_end = int(n * train_frac)
val_end = int(n * (train_frac + val_frac))

df["split"] = "train"
df.loc[train_end:val_end, "split"] = "val"
df.loc[val_end:, "split"] = "test"

feature_cols = (
    ["latitude", "longitude", "depth", "dmin", "rms", "gap", "year",
     "month_sin", "month_cos", "day_sin", "day_cos", "hour_sin", "hour_cos",
     "distance_from_center_km", "past_events_within_100km", "recent_local_events_30d"]
    + list(magtype_dummies.columns)
)
target_col = "mag"

train_df = df[df["split"] == "train"].copy()
val_df = df[df["split"] == "val"].copy()
test_df = df[df["split"] == "test"].copy()

print(f"Train: {len(train_df):,} | Val: {len(val_df):,} | Test: {len(test_df):,}")
print(f"Features used ({len(feature_cols)}): {feature_cols}")

X_train, y_train = train_df[feature_cols], train_df[target_col]
X_val, y_val = val_df[feature_cols], val_df[target_col]
X_test, y_test = test_df[feature_cols], test_df[target_col]

"""## 7. Scaling"""

scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_val_scaled = scaler.transform(X_val)
X_test_scaled = scaler.transform(X_test)

# Keep DataFrame versions around (with proper column names) for SHAP later
X_train_scaled_df = pd.DataFrame(X_train_scaled, columns=feature_cols, index=X_train.index)
X_val_scaled_df = pd.DataFrame(X_val_scaled, columns=feature_cols, index=X_val.index)
X_test_scaled_df = pd.DataFrame(X_test_scaled, columns=feature_cols, index=X_test.index)

"""## 8. Baseline and Machine Learning Models"""

def evaluate(y_true, y_pred):
    return {
        "MAE": mean_absolute_error(y_true, y_pred),
        "RMSE": mean_squared_error(y_true, y_pred) ** 0.5,
        "R2": r2_score(y_true, y_pred),
    }

results = {}

# Baseline: predict the training mean for everything
baseline_pred_val = np.full(len(y_val), y_train.mean())
baseline_pred_test = np.full(len(y_test), y_train.mean())
results["Baseline"] = {
    "val": evaluate(y_val, baseline_pred_val),
    "test": evaluate(y_test, baseline_pred_test),
}

# Linear Regression
lr = LinearRegression()
lr.fit(X_train_scaled, y_train)
results["Linear Regression"] = {
    "val": evaluate(y_val, lr.predict(X_val_scaled)),
    "test": evaluate(y_test, lr.predict(X_test_scaled)),
}

# Random Forest (untuned)
rf = RandomForestRegressor(n_estimators=200, random_state=RANDOM_STATE, n_jobs=-1)
rf.fit(X_train_scaled, y_train)
results["Random Forest"] = {
    "val": evaluate(y_val, rf.predict(X_val_scaled)),
    "test": evaluate(y_test, rf.predict(X_test_scaled)),
}

# XGBoost (untuned)
xgb_model = xgb.XGBRegressor(n_estimators=200, random_state=RANDOM_STATE, n_jobs=-1)
xgb_model.fit(X_train_scaled, y_train)
results["XGBoost"] = {
    "val": evaluate(y_val, xgb_model.predict(X_val_scaled)),
    "test": evaluate(y_test, xgb_model.predict(X_test_scaled)),
}

results_df = pd.DataFrame({
    model: {
        "Val MAE": r["val"]["MAE"], "Val RMSE": r["val"]["RMSE"], "Val R2": r["val"]["R2"],
        "Test MAE": r["test"]["MAE"], "Test RMSE": r["test"]["RMSE"], "Test R2": r["test"]["R2"],
    }
    for model, r in results.items()
}).T
results_df

"""## 9. Hyperparameter Tuning (Expanding-Window Temporal CV)
Uses `TimeSeriesSplit` (5 folds) so every validation fold is strictly later in time
than the training fold that precedes it -- an expanding-window design.

"""

tscv = TimeSeriesSplit(n_splits=5)

# --- Random Forest tuning ---
rf_param_grid = {
    "n_estimators": [200, 300],
    "max_depth": [10, 15, None],
    "min_samples_split": [2, 5],
    "min_samples_leaf": [1, 2],
}
rf_grid = GridSearchCV(
    RandomForestRegressor(random_state=RANDOM_STATE, n_jobs=-1),
    rf_param_grid, cv=tscv, scoring="neg_root_mean_squared_error", n_jobs=-1, verbose=1
)
rf_grid.fit(X_train_scaled, y_train)
print("Best RF params:", rf_grid.best_params_)
print("Best RF CV RMSE:", -rf_grid.best_score_)

tuned_rf = rf_grid.best_estimator_
results["Tuned Random Forest"] = {
    "val": evaluate(y_val, tuned_rf.predict(X_val_scaled)),
    "test": evaluate(y_test, tuned_rf.predict(X_test_scaled)),
}

# --- XGBoost tuning ---
xgb_param_grid = {
    "n_estimators": [200, 300],
    "max_depth": [4, 5, 6],
    "learning_rate": [0.02, 0.05],
    "subsample": [0.8, 0.9],
    "colsample_bytree": [0.7, 0.9],
    "min_child_weight": [3, 5],
}
xgb_random = GridSearchCV(
    xgb.XGBRegressor(random_state=RANDOM_STATE, n_jobs=-1),
    xgb_param_grid, cv=tscv, scoring="neg_root_mean_squared_error", n_jobs=-1, verbose=1
)
xgb_random.fit(X_train_scaled, y_train)
print("Best XGB params:", xgb_random.best_params_)
print("Best XGB CV RMSE:", -xgb_random.best_score_)

tuned_xgb = xgb_random.best_estimator_
results["Tuned XGBoost"] = {
    "val": evaluate(y_val, tuned_xgb.predict(X_val_scaled)),
    "test": evaluate(y_test, tuned_xgb.predict(X_test_scaled)),
}

results_df = pd.DataFrame({
    model: {
        "Val MAE": r["val"]["MAE"], "Val RMSE": r["val"]["RMSE"], "Val R2": r["val"]["R2"],
        "Test MAE": r["test"]["MAE"], "Test RMSE": r["test"]["RMSE"], "Test R2": r["test"]["R2"],
    }
    for model, r in results.items()
}).T
