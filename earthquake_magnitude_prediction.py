"""## 2. Data Collection — USGS Earthquake Catalog API

We pull real events from the USGS FDSN event API (`https://earthquake.usgs.gov/fdsnws/event/1/query`).
The API caps a single request at 20,000 rows, so we query **year by year** and concatenate.

Parameters below (`MIN_MAGNITUDE`, `START_YEAR`, `END_YEAR`) control dataset size — the defaults
pull global M4.5+ events from 1970 to today, which comfortably exceeds 100,000 raw events.
Feel free to tighten `MIN_MAGNITUDE` upward if you want a smaller/faster run.

"""

MIN_MAGNITUDE = 4.5
START_YEAR = 1970
END_YEAR = pd.Timestamp.today().year

BASE_URL = "https://earthquake.usgs.gov/fdsnws/event/1/query"

def fetch_year(year, min_mag=MIN_MAGNITUDE, max_retries=3):
    params = {
        "format": "csv",
        "starttime": f"{year}-01-01",
        "endtime": f"{year}-12-31",
        "minmagnitude": min_mag,
        "orderby": "time-asc",
    }
    for attempt in range(max_retries):
        try:
            r = requests.get(BASE_URL, params=params, timeout=60)
            r.raise_for_status()
            from io import StringIO
            df_year = pd.read_csv(StringIO(r.text))
            return df_year
        except Exception as e:
            print(f"  retry {attempt+1} for {year}: {e}")
            time.sleep(3)
    print(f"  WARNING: failed to fetch {year}, skipping")
    return pd.DataFrame()

frames = []
for yr in range(START_YEAR, END_YEAR + 1):
    print(f"Fetching {yr} ...", end=" ")
    df_yr = fetch_year(yr)
    print(f"{len(df_yr)} events")
    if len(df_yr):
        frames.append(df_yr)
    time.sleep(0.5)  # be polite to the API

raw_df = pd.concat(frames, ignore_index=True)
