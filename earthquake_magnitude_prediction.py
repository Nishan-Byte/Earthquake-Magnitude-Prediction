"""## 12. Magnitude-Range Error Analysis"""

def mag_bin(m):
    if m < 4: return "M3-<4"
    elif m < 5: return "M4-<5"
    elif m < 6: return "M5-<6"
    elif m < 7: return "M6-<7"
    elif m < 8: return "M7-<8"
    else: return "M8+"

